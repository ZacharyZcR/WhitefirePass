/** 他自己记得的罪（不知道自己伤害过谁的那些不算） */
export const sinsBy = (name: string) => SINS.filter((s) => s.by === name && s.knows !== 'none' && s.deed);

/** 别人对他犯下的罪：山灵会说给烙印者听 */
export const sinsAgainst = (name: string) => SINS.filter((s) => s.against.includes(name));

/** 山灵的低语：烙印者在第一夜听到（夜里可以去讨），背誓者在堕落那天听到（白天让他们进火里） */
/** 两个人之间有没有血债（谁欠谁都算） */
export const hasBlood = (a: string, b: string): boolean =>
  SINS.some((s) => (s.by === a && s.against.includes(b)) || (s.by === b && s.against.includes(a)));

/** 欠他血债的人：按债主归拢，每人一条或几条真相（第三夜之后烙印者眼里的"牵连"） */
export function debtsOf(name: string): { target: string; truths: string[] }[] {
  const byDebtor = new Map<string, string[]>();
  for (const s of sinsAgainst(name)) byDebtor.set(s.by, [...(byDebtor.get(s.by) ?? []), s.truth]);
  return [...byDebtor].map(([target, truths]) => ({ target, truths }));
}

export function shanlingWhisper(name: string, canKill = true): string {
  const truths = sinsAgainst(name).map((s) => s.truth);
  const how = canKill ? '夜里，你可以去讨。' : '你的手够不到他们的喉咙——可白天，你可以让他们一个个被推进火里。';
  return `你听见了。白火里有声音，只对你一个人说话——\n\n${truths.join('\n\n')}\n\n他们都在这里，就坐在你身边，对你笑，和你分一块面包。他们欠你的，没有人还过。山庄会替你记着。${how}`;
}
